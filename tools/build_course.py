#!/usr/bin/env python3
"""Twig School course builder — kultrshok x Twig.

Turns courses/<name>/course.md into courses/<name>/course.js + index.html,
and rebuilds courses/catalog.js for the launcher page.

Usage (from the TwigSchool folder):
    python tools/build_course.py            # build every course
    python tools/build_course.py math       # build one course

No third-party packages needed. See README.md for the course.md format.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COURSES = ROOT / "courses"

PAGE_HTML = """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="icon" href="../../framework/assets/twig-icon.png">
<link rel="stylesheet" href="../../framework/twig-theme.css">
</head><body>
<noscript>This workshop needs JavaScript turned on.</noscript>
<script src="../../framework/twig-engine.js"></script>
<script src="../../framework/twig-widgets.js"></script>
<script src="course.js"></script>
<script>TwigSchool.boot(TWIG_COURSE);</script>
</body></html>
"""


def slug(s, used):
    b = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:48] or "page"
    s2, n = b, 2
    while s2 in used:
        s2, n = f"{b}-{n}", n + 1
    used.add(s2)
    return s2


def front_matter(text):
    meta = {}
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
        text = text[m.end():]
    return meta, text


def split_sections(text, level):
    """Split text on headings of exactly `level` #'s, ignoring fenced blocks."""
    out, cur_title, cur, fenced = [], None, [], False
    pat = re.compile(r"^" + "#" * level + r"\s+(.*)$")
    for line in text.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
        m = None if fenced else pat.match(line)
        if m:
            out.append((cur_title, "\n".join(cur).strip()))
            cur_title, cur = m.group(1).strip(), []
        else:
            cur.append(line)
    out.append((cur_title, "\n".join(cur).strip()))
    return out


def is_tracked(title):
    return bool(re.match(r"^(Week \d+|Phase \d+ Checkpoint|Final Boss)", title))


def build(course_dir):
    src = course_dir / "course.md"
    meta, text = front_matter(src.read_text(encoding="utf-8"))
    # drop the H1 title and an optional byline right under it
    h1 = re.search(r"^#\s+(.*)$", text, re.M)
    title = meta.get("title") or (h1.group(1) if h1 else course_dir.name)
    if h1:
        text = text[h1.end():]
    used, pages, seen_split = set(), [], False
    for gtitle, body in split_sections(text, 2):
        if gtitle is None:
            continue
        subs = split_sections(body, 3)
        if any(t and re.match(r"Week \d+", t) for t, _ in subs):
            seen_split = True
            intro = subs[0][1]
            if intro:
                pages.append(dict(group=gtitle, title="Phase overview", md=intro, track=False))
            for t, b in subs[1:]:
                pages.append(dict(group=gtitle, title=t, md=b, track=is_tracked(t)))
        else:
            grp = "Toolbox" if seen_split else "Start here"
            pages.append(dict(group=grp, title=gtitle, md=body, track=False))
    for p in pages:
        p["id"] = slug(p["title"] if p["title"] != "Phase overview" else p["group"], used)
    course = dict(id=meta.get("id", course_dir.name), title=title,
                  subtitle=meta.get("subtitle", ""), home=meta.get("home", "../../index.html"),
                  pages=[{k: p[k] for k in ("id", "group", "title", "md", "track")} for p in pages])
    js = "/* Generated by tools/build_course.py from course.md. Edit course.md, not this file. */\n"
    js += "window.TWIG_COURSE = " + json.dumps(course, ensure_ascii=False, indent=1) + ";\n"
    (course_dir / "course.js").write_text(js, encoding="utf-8")
    (course_dir / "index.html").write_text(PAGE_HTML.format(title=title), encoding="utf-8")
    tracked = sum(p["track"] for p in pages)
    print(f"built {course_dir.name}: {len(pages)} pages, {tracked} tracked")
    return dict(id=course["id"], dir=course_dir.name, title=title, subtitle=course["subtitle"],
                blurb=meta.get("blurb", ""), order=int(meta.get("order", 99)))


def main():
    names = sys.argv[1:]
    dirs = [COURSES / n for n in names] if names else sorted(d for d in COURSES.iterdir() if (d / "course.md").exists())
    for d in dirs:
        build(d)
    # catalog always lists every course
    cat = []
    for d in sorted(x for x in COURSES.iterdir() if (x / "course.md").exists()):
        meta, _ = front_matter((d / "course.md").read_text(encoding="utf-8"))
        cat.append(dict(id=meta.get("id", d.name), dir=d.name, title=meta.get("title", d.name),
                        subtitle=meta.get("subtitle", ""), blurb=meta.get("blurb", ""), order=int(meta.get("order", 99))))
    cat.sort(key=lambda c: c["order"])
    (COURSES / "catalog.js").write_text("window.TWIG_CATALOG = " + json.dumps(cat, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"catalog: {len(cat)} courses")


if __name__ == "__main__":
    main()
